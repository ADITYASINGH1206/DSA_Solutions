/**
 * Problem: Find the Maximum Achievable Number (2769)
 * Link: https://leetcode.com/problems/find-the-maximum-achievable-number/
 * Difficulty: Easy
 */

#include <bits/stdc++.h>
using namespace std;

class Solution {
public:
    int theMaximumAchievableX(int num, int t) {
        return num+2*t;
    }
};
